"""Generate the example's pinned Phosphor subset and Rust glyph map."""

from hashlib import sha256
from io import BytesIO
from pathlib import Path
import re
from urllib.request import urlopen

from fontTools import subset, version
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parent
REVISION = "70854726d7bd82ae21f0dc81b5b5c35240a77066"  # web v2.1.2
BASE = f"https://raw.githubusercontent.com/phosphor-icons/web/{REVISION}"
SOURCES = {
    "src/regular/Phosphor.ttf": "06b91e022b7ee899a63efced879392a74f0bacbda54e4467e9f663220d173a10",
    "src/regular/style.css": "873761b8711147dc516b6102936e9ad005f3a3015349efcde1a496f0326f1051",
    "LICENSE": "687fbe52d0eb5c2353eca27a4037e889145ee0b584d3b1abf67581c4a4a4e47c",
}
GLYPHS = {
    "ARCHIVE": "archive-box",
    "ENVELOPE": "envelope",
    "PLUS": "plus",
    "TRASH": "trash",
}


def read_source(path):
    with urlopen(f"{BASE}/{path}", timeout=30) as response:
        data = response.read()
    if sha256(data).hexdigest() != SOURCES[path]:
        raise ValueError(f"Unexpected source bytes: {path}")
    return data


def make_subset(source, points):
    font = TTFont(BytesIO(source), recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=list(points))
    subsetter.subset(font)
    if set(font.getBestCmap()) != set(points):
        raise ValueError("Subset cmap differs from the pinned glyph map")
    output = BytesIO()
    font.save(output, reorderTables=True)
    return output.getvalue()


def main():
    if version != "4.68.0":
        raise ValueError("Use fonttools==4.68.0 to reproduce this asset")
    source = read_source("src/regular/Phosphor.ttf")
    css = read_source("src/regular/style.css").decode()
    license_text = read_source("LICENSE")
    codepoints = {}
    for constant, name in GLYPHS.items():
        pattern = rf'\.ph\.ph-{name}:before\s*\{{\s*content:\s*"\\([0-9a-f]+)"'
        match = re.search(pattern, css)
        if match is None:
            raise ValueError(f"Missing upstream glyph: {name}")
        codepoints[constant] = int(match[1], 16)
    binary = make_subset(source, codepoints.values())
    lines = ["// Generated by assets/prepare_phosphor.py from Phosphor Regular v2.1.2."]
    for constant, point in codepoints.items():
        lines.append(f"pub(super) const {constant}: char = '\\u{{{point:x}}}';")
    (ROOT / "Phosphor-Mail-Regular.ttf").write_bytes(binary)
    (ROOT / "PHOSPHOR-LICENSE.txt").write_bytes(license_text)
    (ROOT.parent / "phosphor" / "glyphs.rs").write_text("\n".join(lines) + "\n")
    print(f"{len(codepoints)} glyphs, {len(binary)} bytes, SHA-256 {sha256(binary).hexdigest()}")


if __name__ == "__main__":
    main()
