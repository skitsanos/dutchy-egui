//! Session settings; credentials remain in the ignored environment file.
use crate::{
    app::App,
    provider::{Mode, Scenario},
};
use dutchy_egui::{
    Drawer, DrawerWidth, Field, Input, OverlayOptions, Segmented, Select, SelectOption, Switch,
    Text, TextColor, Textarea, tokens::space,
};
use egui::Context;

pub(crate) fn show(app: &mut App, ctx: &Context) {
    let mut open = app.settings_open;
    Drawer::new("agent-settings", &mut open, "Chat settings")
        .width(DrawerWidth::Large)
        .options(OverlayOptions {
            return_focus: app.settings_return,
            ..Default::default()
        })
        .show(ctx, |ui| {
            let mut provider = Some(app.config.provider);
            let providers = [
                SelectOption::new(Mode::OpenAi, "OpenAI"),
                SelectOption::new(Mode::Mock, "Offline mock"),
            ];
            Field::new("Provider")
                .help(
                    "Changes apply to new requests. Running replies keep their original provider.",
                )
                .show(ui, |ui| {
                    ui.add(Select::new("chat-provider", &mut provider, &providers))
                });
            if let Some(provider) = provider {
                app.config.provider = provider;
            }
            ui.add(
                Text::new(if app.config.provider == Mode::Mock {
                    "Scripted examples. No requests are sent."
                } else {
                    "Replies are generated by your configured OpenAI model."
                })
                .color(TextColor::Muted),
            );
            ui.add_space(space::LG);
            Field::new("Model name").show(ui, |ui| {
                ui.add(Input::new("model-name", &mut app.config.model).char_limit(128))
            });
            let mut effort = Some(app.config.effort.clone());
            let options = [
                SelectOption::new("low".to_owned(), "Low"),
                SelectOption::new("medium".to_owned(), "Medium"),
                SelectOption::new("high".to_owned(), "High"),
            ];
            Field::new("Model effort").show(ui, |ui| {
                ui.add(Segmented::new("model-effort", &mut effort, &options).full_width(true))
            });
            if let Some(effort) = effort {
                app.config.effort = effort;
            }
            ui.add_space(space::LG);
            ui.add(Text::label("OPENAI_API_KEY"));
            ui.add(
                Text::new(if app.config.key_configured {
                    "•••••••• · configured"
                } else {
                    "Not configured · optional for offline use"
                })
                .color(TextColor::Muted),
            );
            ui.add_space(space::LG);
            ui.add(Switch::new(
                "chat-streaming",
                &mut app.config.streaming,
                "Stream replies",
            ));
            if app.config.provider == Mode::Mock {
                let mut scenario = Some(app.scenario);
                let scenarios: Vec<_> = Scenario::ALL
                    .into_iter()
                    .map(|v| SelectOption::new(v, v.label()))
                    .collect();
                Field::new("Mock response scenario").show(ui, |ui| {
                    ui.add(Select::new("mock-scenario", &mut scenario, &scenarios))
                });
                if let Some(scenario) = scenario {
                    app.scenario = scenario;
                }
            }
            ui.add_space(space::LG);
            Field::new("System prompt")
                .help("Session only. OpenAI receives this instruction with each new request.")
                .show(ui, |ui| {
                    ui.add(
                        Textarea::new("system-prompt", &mut app.config.system_prompt)
                            .rows(3)
                            .char_limit(2_000),
                    )
                });
            ui.add_space(space::LG);
            ui.add(Text::label("Appearance"));
            app.theme.controls(ui);
        });
    app.settings_open = open;
}
